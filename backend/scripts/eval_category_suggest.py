"""Evaluate category suggestion on the generated test set and write a report.

    cd backend && python scripts/eval_category_suggest.py            # prints, writes docs/category-suggest-accuracy.md
    python scripts/generate_category_eval_data.py                    # regenerate the rows first, if needed

Runs the real model (bge-small-en-v1.5 via app/categories_suggest.py) with the production threshold and
margin. Two settings on the same rows:
  base      the 11 calibration categories; rows about other categories must get no suggestion
  extended  base + 5 temporary categories (Pet Supplies, Garden Tools, Board Games, Art Supplies, Toys),
            which exist only in memory for this run. Nothing is written to the database.
"""
import pathlib
import sys
from datetime import date

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

from app.categories_suggest import BgeEmbedder  # noqa: E402
from app.matching.trigger import model_dir  # noqa: E402
from calibrate_category_suggest import EXAMPLES  # noqa: E402
from category_suggest_eval import (BASE_CATS, CSV_PATH, EXTRA_CATS, MARGIN, THRESHOLD,  # noqa: E402
                                   calibration_rows, evaluate, load_rows, rankings, sweep)

REPORT = ROOT.parent / "docs" / "category-suggest-accuracy.md"


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def main() -> None:
    emb = BgeEmbedder(model_dir())
    rows = load_rows()
    cal = calibration_rows()
    extended_cats = BASE_CATS + EXTRA_CATS

    base = evaluate(rows, rankings(emb, rows, BASE_CATS, EXAMPLES), BASE_CATS)
    base_sweep = sweep(rows, rankings(emb, rows, BASE_CATS, EXAMPLES), BASE_CATS)
    ext_ranked = rankings(emb, rows, extended_cats, EXAMPLES)   # extra categories have no example listings yet
    ext = evaluate(rows, ext_ranked, extended_cats)
    cal_m = evaluate(cal, rankings(emb, cal, BASE_CATS, EXAMPLES), BASE_CATS)

    lines = [
        "# Category suggestion: accuracy report",
        "",
        f"Date: {date.today().isoformat()}. Model: BAAI/bge-small-en-v1.5 (int8 ONNX), CLS pooling, query instruction on the title.",
        f"Production settings: threshold {THRESHOLD}, margin {MARGIN} (`app/config.py`). Examples per category: up to 20 recent titles (calibration examples in `scripts/calibrate_category_suggest.py`).",
        f"Test data: `{CSV_PATH.relative_to(ROOT)}`, {len(rows)} rows, generated by `scripts/generate_category_eval_data.py` (fixed seed).",
        "",
        "## Limitations",
        "",
        "- The test titles are synthetic (templates plus typing noise). Real listings are messier, so expect lower accuracy on them.",
        "- Labels come from the generator and were not reviewed by a person. Cross-category titles can be ambiguous.",
        "- The five extra categories have no example listings, so they are compared by name only. Real new categories also start this way.",
        "- The example listings are the calibration examples, which are real titles from the seed data.",
        "",
        "## Data",
        "",
        "| Tier | Rows | Meaning |",
        "|---|---|---|",
    ]
    tier_meaning = {"easy": "generated from category product words, with typing noise",
                    "hard": "brands, models, synonyms, or titles that fit two categories",
                    "none": "nothing fits, or only about a category not in the list"}
    counts = {}
    for r in rows:
        counts[r["tier"]] = counts.get(r["tier"], 0) + 1
    for t in ("easy", "hard", "none"):
        lines.append(f"| {t} | {counts.get(t, 0)} | {tier_meaning[t]} |")
    lines += ["", f"Calibration titles (baseline, used to choose the thresholds, so not held out): {len(cal)} rows.", ""]

    def block(title, m, note):
        return [
            f"## {title}", "", note, "",
            "| Metric | Value |", "|---|---|",
            f"| Rows tested | {m['rows']} ({m['positives']} with a fitting category, {m['negatives']} with none) |",
            f"| Top pick is a gold category (ranking, ignores threshold) | {pct(m['top1_accuracy'])} |",
            f"| Suggestions made | {m['suggested']} |",
            f"| Correct suggestions | {m['correct_suggestions']} |",
            f"| Precision (correct / suggested) | {pct(m['precision'])} |",
            f"| Recall (correct / rows with a fitting category) | {pct(m['recall'])} |",
            f"| F1 | {pct(m['f1'])} |",
            f"| Macro F1 over categories | {pct(m['macro_f1'])} |",
            f"| Stayed quiet on rows with no fitting category | {pct(m['abstain_on_negatives'])} |",
            f"| Overall decision accuracy | {pct(m['decision_accuracy'])} |",
            "",
            "By tier:", "",
            "| Tier | Rows | Correct decisions |", "|---|---|---|",
        ] + [f"| {t} | {v['rows']} | {pct(v['accuracy'])} |" for t, v in m["by_tier"].items()] + [""]

    lines += block("Base: 11 categories", base,
                   "Rows about the five extra categories count as negatives here, so a suggestion for them is an error.")
    lines += ["Threshold sweep (base, margin 0.03):", "",
              "| Threshold | Suggestions | Correct | Precision | Recall | Quiet on negatives |", "|---|---|---|---|---|---|"]
    lines += [f"| {t:.2f} | {s} | {c} | {pct(p)} | {pct(r)} | {pct(q)} |" for t, s, c, p, r, q in base_sweep]
    lines += [""]
    lines += block("Extended: 16 categories (5 temporary)", ext,
                   "Five categories with no example listings: only the category name is compared. Titles for these must now be suggested.")
    lines += ["Per-category F1 (extended):", "", "| Category | F1 |", "|---|---|"]
    lines += [f"| {c} | {pct(v)} |" for c, v in ext["per_category_f1"].items()] + [""]
    lines += ["Most common wrong suggestions (extended): gold category(ies) -> suggested category, count:", ""]
    lines += [f"- {' / '.join(g)} -> {p}: {n}" for (g, p), n in ext["top_confusions"]] or ["- none"]
    lines += [""]
    lines += ["Sample wrong suggestions (extended), first 15:", "", "| Title | Gold | Suggested | Top score |", "|---|---|---|---|"]
    lines += [f"| {t} | {', '.join(g) or '(none)'} | {p} | {s} |" for t, g, p, s in ext["wrong_suggestions"][:15]]
    lines += [""]
    lines += block("Calibration baseline: 87 titles, base categories", cal_m,
                   "Same titles the thresholds were tuned on. Included for comparison with the held-out generated set.")

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines))
    print("\n".join(lines))
    print(f"\nreport written to {REPORT}")


if __name__ == "__main__":
    main()
