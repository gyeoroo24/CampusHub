"""Evaluate automatic flagging of Buy & Sell listings on the generated test set and write a report.

    cd backend && python scripts/eval_auto_flag.py       # prints, writes docs/auto-flag-accuracy.md

Runs the production checks in app/screening.py (prohibited item, gibberish title, spam) with the real
bge-small model. Regenerate the data first if needed: python scripts/generate_auto_flag_eval_data.py
"""
import asyncio
import pathlib
import sys
from datetime import date

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests"))

import auto_flag_eval as ev  # noqa: E402
import app.screening as sc  # noqa: E402
from app.categories_suggest import suggestion_available  # noqa: E402

REPORT = ROOT.parent / "docs" / "auto-flag-accuracy.md"


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def metric_rows(m: dict) -> list[str]:
    return [
        f"| Rows | {m['n']} ({m['positives']} positive, {m['negatives']} negative) |",
        f"| Precision | {pct(m['precision'])} |",
        f"| Recall | {pct(m['recall'])} |",
        f"| F1 | {pct(m['f1'])} |",
        f"| Accuracy | {pct(m['accuracy'])} |",
        f"| False-positive rate (flagged a fine post) | {pct(m['false_positive_rate'])} |",
        f"| Missed (false negatives) | {m['fn']} |",
    ]


def main() -> None:
    if not suggestion_available():
        raise SystemExit("bge-small model not available: python scripts/fetch_match_models.py --suggest-only")
    listings = ev.load_listings()
    spam = ev.load_spam()
    gold_p = [bool(r["prohibited"]) for r in listings]
    gold_g = [bool(r["gibberish"]) for r in listings]

    prohibited, gibberish = ev.run_listings(listings)
    scores = ev.prohibited_scores([r["title"] for r in listings])
    sim_only = ev.similarity_only(scores)
    m_p = ev.binary(gold_p, prohibited)
    m_sim = ev.binary(gold_p, sim_only)
    m_g = ev.binary(gold_g, gibberish)
    gold_any = [a or b for a, b in zip(gold_p, gold_g)]
    pred_any = [a or b for a, b in zip(prohibited, gibberish)]
    m_any = ev.binary(gold_any, pred_any)
    m_spam, spam_by_kind, spam_errors = asyncio.run(ev.evaluate_spam(spam))

    tiers = {}
    for r, p, g in zip(listings, prohibited, gibberish):
        t = tiers.setdefault(r["tier"], [0, 0, 0])
        t[0] += 1
        t[1] += bool(p)
        t[2] += bool(g)
    rec_full = ev.group_recall(listings, prohibited, "group")
    rec_sim = ev.group_recall(listings, sim_only, "group")
    sweep = ev.sweep(listings, scores)

    L = [
        "# Automatic flagging (Buy & Sell): accuracy report",
        "",
        f"Date: {date.today().isoformat()}. Checks: `app/screening.py` (prohibited item, gibberish title, spam).",
        f"Prohibited item: word list, then bge-small similarity to {len(sc.PROHIBITED)} "
        f"prohibited descriptions and {len(sc.HARMLESS)} harmless look-alikes. "
        f"Production settings: similarity >= {ev.PROHIBITED_AT} and a lead of at least {sc.PROHIBITED_LEAD} over the best look-alike.",
        f"Test data: `{ev.LISTINGS_CSV.relative_to(ROOT)}` ({len(listings)} listings) and `{ev.SPAM_JSON.relative_to(ROOT)}` "
        f"({len(spam)} spam scenarios), generated by `scripts/generate_auto_flag_eval_data.py` (fixed seed).",
        "",
        "## Limitations",
        "",
        "- Synthetic titles from templates, labelled by the generator and not reviewed by a person. Real listings are messier.",
        "- Only listing titles are checked here. Descriptions, Lost & Found reports and the photo check (NSFW model) are not in this report.",
        "- Spam uses stubbed histories. The 24-hour window itself is enforced in SQL and is not tested here.",
        "- The prohibited check is only as broad as its descriptions. Illegal items not described in `PROHIBITED` will be missed.",
        "- The drug slang rules were written after seeing the `drugs_slang` group, so that group is optimistic. "
        "`drugs_slang_heldout` uses terms the rules did not include, and is the honest figure for slang.",
        "",
        "## Data",
        "",
        "| Tier | Listings | Meaning |",
        "|---|---|---|",
    ]
    meaning = {"prohibited": "illegal or banned items, some with slang and no banned word",
               "lookalike": "harmless items close to a prohibited one (must not be flagged)",
               "clean": "ordinary listings from the category test set",
               "gibberish": "keyboard runs, repeated letters, consonant clusters, random strings",
               "real": "short real titles with brands and models (must pass the gibberish check)"}
    for t in ("prohibited", "lookalike", "clean", "gibberish", "real"):
        L.append(f"| {t} | {tiers.get(t, [0])[0]} | {meaning[t]} |")
    L += ["", "## 1. Prohibited item (listings)", "", "Full production check (word list, then similarity).", "",
          "| Metric | Value |", "|---|---|"] + metric_rows(m_p) + [""]
    L += ["Recall by group (full check, then similarity only):", "",
          "| Group | Posts | Caught (full) | Recall (full) | Caught (similarity only) | Recall (similarity only) |",
          "|---|---|---|---|---|---|"]
    for g, (n, k, rate) in rec_full.items():
        ks = rec_sim.get(g, (n, 0, 0))[1]
        L.append(f"| {g} | {n} | {k} | {pct(rate)} | {ks} | {pct(ks / n)} |")
    L += ["", f"Similarity only (no word list), threshold sweep, lead {sc.PROHIBITED_LEAD}:", "",
          "| Threshold | Precision | Recall | False-positive rate |", "|---|---|---|---|"]
    L += [f"| {t:.2f} | {pct(p)} | {pct(r)} | {pct(fpr)} |" for t, p, r, fpr in sweep]
    L += ["", f"Similarity alone at the production threshold ({ev.PROHIBITED_AT}): precision {pct(m_sim['precision'])}, "
          f"recall {pct(m_sim['recall'])}, false-positive rate {pct(m_sim['false_positive_rate'])}.", ""]
    L += ["## 2. Gibberish title", "", "| Metric | Value |", "|---|---|"] + metric_rows(m_g) + [""]
    L += ["## 3. Spam", "", "Stub history (see limitations). A scenario is spam when the new post is the third "
          "near-identical one in 24 hours, or the ninth in an hour.", "",
          "| Metric | Value |", "|---|---|"] + metric_rows(m_spam) + [""]
    L += ["By scenario type:", "", "| Scenario | Scenarios | Correct | Accuracy |", "|---|---|---|---|"]
    L += [f"| {k} | {n} | {c} | {pct(a)} |" for k, (n, c, a) in spam_by_kind.items()] + [""]
    L += ["## 4. Listing as a whole", "",
          "Flagged if the prohibited or gibberish check fires. Gold: prohibited or gibberish.", "",
          "| Metric | Value |", "|---|---|"] + metric_rows(m_any)
    L += ["", f"Held from other users (prohibited check fired): {sum(prohibited)} of {len(listings)} listings.", ""]
    L += ["Flag rate by tier:", "", "| Tier | Listings | Held (prohibited) | Gibberish |", "|---|---|---|---|"]
    L += [f"| {t} | {n} | {p} | {g} |" for t, (n, p, g) in tiers.items()] + [""]

    fn = [(r["title"], r["source"]) for r, p in zip(listings, prohibited) if r["prohibited"] and not p]
    fp = [(r["title"], r["tier"]) for r, p in zip(listings, prohibited) if not r["prohibited"] and p]
    gfn = [r["title"] for r, g in zip(listings, gibberish) if r["gibberish"] and not g]
    gfp = [r["title"] for r, g in zip(listings, gibberish) if not r["gibberish"] and g]
    L += [f"## 5. Errors", "", f"Missed prohibited items ({len(fn)}), first 15:", "",
          "| Title | Source |", "|---|---|"] + [f"| {t} | {s} |" for t, s in fn[:15]] + [""]
    L += [f"Prohibited check false alarms ({len(fp)}), first 15:", "", "| Title | Tier |", "|---|---|"]
    L += [f"| {t} | {s} |" for t, s in fp[:15]] + [""]
    L += [f"Gibberish misses ({len(gfn)}): {', '.join(gfn[:20]) or 'none'}", ""]
    L += [f"Gibberish false alarms ({len(gfp)}): {', '.join(gfp[:20]) or 'none'}", ""]
    L += [f"Spam scenario errors ({len(spam_errors)}), first 15:", "", "| Scenario | Post | Gold spam | Predicted reason |",
          "|---|---|---|---|"]
    L += [f"| {k} | {t} | {'yes' if g else 'no'} | {reason or 'not flagged'} |" for k, t, g, reason in spam_errors[:15]]

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"\nreport written to {REPORT}")


if __name__ == "__main__":
    main()
