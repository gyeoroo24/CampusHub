def generate_locustfile_content(
    selected_ids: List[str],
    weights: Dict[str, int],
    token: str = ""
) -> str:
    """Generate the full Python code string for the custom locustfile."""
    content = TEMPLATE_HEADER.replace("__EMBEDDED_TOKEN__", token)
    
    # Append selected tasks using string replacement to avoid any f-string/brace conflicts
    for ep_id in selected_ids:
        ep = ENDPOINTS_MAP.get(ep_id)
        if not ep:
            continue
        weight = weights.get(ep_id, ep.default_weight)
        if weight <= 0:
            continue
        task_code = ep.code_template.replace("{weight}", str(weight))
        content += "\n" + task_code + "\n"
        
    return content


def save_locustfile(
    output_path: str,
    selected_ids: List[str],
    weights: Dict[str, int],
    token: str = ""
) -> str:
    """Generate and write the locustfile to disk."""
    code = generate_locustfile_content(selected_ids, weights, token)
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(code)
    return output_path
